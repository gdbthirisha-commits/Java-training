// Primitive Data Types – Minimum and Maximum Values in Java

public class primitiveminmax {
    public static void main(String[]args){
        System.out.println("BYTE");
        System.out.println("min="+Byte.MIN_VALUE);
        System.out.println("max="+Byte.MAX_VALUE);
        System.out.println("\nSHORT");
        System.out.println("min="+Short.MIN_VALUE);
        System.out.println("max="+Short.MAX_VALUE);
        System.out.println("\nINT");
        System.out.println("min="+Integer.MIN_VALUE);
        System.out.println("max="+Integer.MAX_VALUE);
        System.out.println("\nCHAR");
        System.out.println("min="+(int)Character.MIN_VALUE);
        System.out.println("max="+(int)Character.MAX_VALUE);
        System.out.println("\n BOOLEAN");
        System.out.println("values=true/false");
    }
    
}
